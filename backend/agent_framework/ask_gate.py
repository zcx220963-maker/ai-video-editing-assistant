"""硬保证：模型向用户提问时**必须**走弹窗，不允许把问题写在正文里。

**为什么需要这一层。** 原先「要不要弹窗」完全由模型自觉决定：
它调 ``ask_user`` 就弹窗，把问题写进正文就只是普通答复，代码根本不检查。
真机实测到过后者——正文里列着「1. 风格：高光金句 / Vlog 三段式…
2. 时长：15 / 30 / 60 秒…」让用户自己打字挑，与弹窗那种点选体验是两回事。

**做法。** 在「准备收尾」那一刻拦截：这段文字是不是在向用户提问？
是，而且本轮没有 ``ask_user`` 调用，就把这轮打回，明确要求它用 ``ask_user`` 重问一遍。
这与项目里已有的「声称出了计划卡但没调 submit_plan 就打回」是同一套做法
（见 ``agent._NO_CARD_STRUCTURAL_NUDGE``），有现成先例。

**为什么判据是「问号 + 索取措辞」而不是只要有问号。**
中文正文里带问号太常见了（反问、设问、「为什么…呢」）。只看问号会把正常答复也打回，
让用户白等一轮。所以要求同时出现**向用户索取信息**的措辞。

**打回次数为什么要有上限。** 模型可能坚持认为自己没在提问。无上限打回会烧穿迭代预算，
所以默认只打回一次；用尽之后如实交付，并在末尾附一句服务端核对到的事实
（``NO_POPUP_NOTE``），让用户知道「这句本该是个弹窗」。
"""
from __future__ import annotations

import re
from typing import Any

# 强索取措辞：这些单独出现（**不带问号**）就足以判定为「在向用户提问」。
#
# 为什么不能要求问号：用户点名的场景恰恰不带问号——「请把视频链接发我」
# 「麻烦你把链接贴给我」「需要你上传一条更长的素材」都是祈使句。
# 所以这里只收「请/要用户做某个具体动作」的措辞，靠动作动词收窄来避免误伤。
#
# `需要你` 后面必须跟动作动词：`需要你知道`／`需要你留意` 是在**告知**，不是提问
# （标定脚本实测：不加这条限制会把「两点需要你知道的偏差」误判成提问）。
_SEEKING = re.compile(
    r"(请你(选|选择|挑|确认|决定|告诉|提供|补充|上传|发|给|说明|回答|把|回复|看)"
    r"|麻烦你|要你(选|告诉|提供|确认|上传|发)"
    r"|需要你(选|选择|挑|确认|决定|告诉|提供|补充|上传|发|给|说明|回答|把|点|回复)"
    r"|你(选|挑|决定)(一个|哪|一下)"
    r"|告诉我(你|要|想|素材|链接)"
    r"|你告诉我"
    r"|(选|挑)(一个|一下|哪一)"
    r"|发(我|给我)|(贴|传)给我"
    r"|把(链接|素材|视频|文件)(发|贴|传|给)"
    r"|(链接|素材)发我|素材在哪|视频在哪|文件在哪"
    r"|(点|选)一下|点选"
    # 注意这里**不能**收「你确认后」「你回复后」：那是说明接下来会发生什么
    # （「给了 1 版计划，等你确认后再开工」），不是让用户此刻做选择。
    r"|请回(复|答)|请你回复)")

# 弱索取措辞：泛泛的第二人称意愿询问，必须**配问号**才算提问。
# 不配问号可能只是叙述（「用户的诉求是…」），单独放行会误伤。
_WEAK_SEEKING = re.compile(
    r"(你(想|要|希望|打算|倾向|更|偏)|要不要我|需不需要我|是否|请|麻烦)")

# 明确的「等你回答」标记：有它就够，不必再看其它条件。
#
# 这里**刻意不收「等你确认」「等你回复」**：模型收尾时爱写
# 「给了 1 版计划，等你确认。」——那是在**告知**「球在你那边」，
# 不是在向用户索取一个新的决定。标定时这类文本把 plan_flow 的四个用例全打回了，
# 所以只保留祈使式（「请/麻烦你 + 动作」）与「等你+动作名词」。
_EXPLICIT = re.compile(r"(请|麻烦)(回复|回答|选择|点选)|你(回复|回答)后|"
                       r"选完(之后|后)|(点|选)(一下|一选)|麻烦点|请你点|点选"
                       r"|请你确认(?![:：])|麻烦你确认(?![:：])"
                       r"|等你(回复|回答|选择|点选|选完)")

# 「你做完 X，我就做 Y」的将来小句：这是在**告知接下来会发生什么**，不是索取。
#
# 真机事故（用户原话「怎么我第一个弹窗的问题还没选完，就继续了然后跳第二次弹窗，
# 第一次都没提交啊」）：规划轮交出计划卡后收尾写「你点选确认后我再开始跑剪辑。」，
# ``_SEEKING`` 里的「点选」直接命中 → ask_gate 把一句告知判成提问、白打回一轮 →
# 模型照着打回改用 ``ask_user`` 重问「你想按哪一版来剪？」（卡上本来就在问这个）→
# 弹窗是单例，这一问把用户正填着的计划确认卡顶掉了，选到一半的答案全丢。
#
# 判据的关键是「动词 + 后/完 + 我/就/再…」：后头跟的是**模型自己的下一步动作**，
# 说明那个动词是在描述流程，不是在要用户此刻回答。只认「你」起头的形式——
# 「请你选后我再开工」这类祈使句不该被中和，那确实是在索取。
_FUTURE_CLAUSE = re.compile(
    r"(?<![请要需烦])你(?:点选|点一下|选一下|选一个|选一选|挑一个|选择|挑|选|确认|回复|回答|决定)"
    r"(?:确认|一下)?(?:完之后|完后|之后|完毕|完|后)"
    r"(?:我|咱|就|再|接着|然后|开始|马上|立刻|便)")


def _neutralize_future_clauses(text: str) -> str:
    """先把「你做完 X 我就做 Y」的将来小句换成占位符，再交给判据。

    只要替换后的残句不再命中任何一条判据即可，不必保留长度。占位符取 ``…``：
    它在四条判据的字符集里都不出现。
    """
    return _FUTURE_CLAUSE.sub("…", text)


# 只在这些情况下才需要「+ 问号」才算提问：单靠措辞可能出现在正常叙述里
_QUESTION_MARK = re.compile(r"[?？]")

# 「我在等你」之外的收尾形态：模型常以「你来定」结尾，也算索取
_TRAILING_ASK = re.compile(r"(你来(定|决定|选)|由你(定|决定|选)|看你(的|想)|听你的)")

# 「在正文里要用户**动嘴/打字**确认一个方案」的收尾形态。
#
# 为什么要单独一条、而不并进 _EXPLICIT：这两件事的**正确出路不同**。
# 提问（要用户拿主意）→ 走 ask_user 弹窗；方案确认 → 走 submit_plan 出计划卡。
# 真机实测：模型把整套方案写成正文，末尾「确认这个方案就回复我」——
# 用户既没拿到可点的计划卡，也被告知"回复我"，只能打字。
# 而 _EXPLICIT 刻意不收「等你确认」（那常出现在告知性收尾里，收了会误伤），
# 所以这类文本一路漏到用户面前。
#
# 判据的关键：必须出现**索取动作**（回复我 / 打字 / 告诉我 / 说一声 / 答复我），
# 光有「请确认」「等你确认」不够——那两句话有两种含义：
#   · 「请确认：先重排时间线再渲染」→ 在**陈述计划内容**，不是要用户说话；
#   · 「确认这个方案就回复我」      → 在**索取打字**，这才是要拦的。
# 所以冒号/分号要排除在「确认 → 动作」之间：冒号后面是解释，不是索取。
# 收得太宽会把「假称已提交」那类文本也打回，白烧一轮迭代预算
# （tests/test_plan_flow 的「核对只用一次」用例实测到过）。
_PLAN_INVITE = re.compile(
    # 「回复」必须带宾语或形成索取：「回复我」算，「一次性回复」不算——
    # 裸的"回复"是普通名词，出现在任何正常句子里都会误命中
    # （tests/test_stream 的「一次性回复」实测被打回过，白烧一轮）。
    r"回复(我|一下|确认|一句)"
    r"|打字|告诉我|说一声|答复我"
    r"|确认[^。；：:\n]{0,10}(就|再|后)?(回复|开工|执行)"
    r"|(方案|计划|这版|版本)[^。；：\n]{0,8}(可以吗|行不行|是否可行|要不要改)"
)


def looks_like_plan_invite(text: Any) -> bool:
    """这段答复是不是把**方案写成正文、然后要用户动嘴/打字来确认**。

    命中即说明模型绕过了计划门：该出卡的时候出了散文。调用方应当把它打回，
    要求改用 ``submit_plan`` 出卡——用户点卡，不必打字。

    刻意**不**把「请确认」「等你确认」单独算作命中：那两句既可能是在索取打字，
    也可能只是在陈述计划内容；后者该由「假称已提交」那道守卫处置，
    混在一起会把正常收尾也打回、白烧一轮。真正可靠的特征是**索取动作**。
    """
    # 同样先中和将来小句：「你确认后我就开工」是**告知**，不是要用户回复；
    # 而「你确认后回复我」那种索取（没有「我就…」的下文）照旧命中。
    return bool(_PLAN_INVITE.search(_neutralize_future_clauses(str(text or ""))))


def looks_like_asking_user(text: Any) -> bool:
    """这段答复是不是在向用户提问 / 索取决定。

    两级判据（由 ``calibrate_ask_gate.py`` 在正反例上标定过）：
      · **强索取**（请你选 / 麻烦你 / 需要你上传 / 把链接发我 / 素材在哪…）
        → 单独出现就算，不强求问号。用户点名的「要素材、贴链接」都是祈使句、不带问号。
      · **弱索取**（你想 / 要不要我 / 是否…）→ 必须配问号才算，
        否则「用户的诉求是…」这类叙述会被误伤。
      · 以「你来定 / 听你的」结尾也算（模型常这么收尾）。

    宁可漏一点也不要误伤：把正常结论判成提问会让用户白等一轮。
    """
    body = _neutralize_future_clauses("" if text is None else str(text))
    if not body.strip():
        return False
    if _SEEKING.search(body):
        return True
    if _WEAK_SEEKING.search(body) and _QUESTION_MARK.search(body):
        return True
    if _EXPLICIT.search(body):
        return True
    if _TRAILING_ASK.search(body[-80:]):
        return True
    return False


# 打回时喂给模型的服务端核对（与 _NO_CARD_STRUCTURAL_NUDGE 同风格：先陈述事实再给两条路）
POPUP_NUDGE = (
    "服务端核对：上面这段是在向用户提问／要用户做决定，但你没有调用 ask_user，"
    "所以界面上**不会**弹出选项卡——用户只能自己打字回答，而且经常答非所问。\n"
    "现在二选一：\n"
    "① 调用 ask_user 把这个问题重新问一遍：title 写清问什么，options 给 2~6 个有真实差异的"
    "选项，把你建议的那个标 recommended=true；用户还能自己写一条。**调用后就停下等用户选**，"
    "不要在同一条回复里替用户把选择也定了。\n"
    "② 如果你其实不需要用户拿主意（信息已经够你判断），就把疑问去掉，直接给出结论，"
    "不要再问。\n"
    "凡是要用户拿主意，就必须是弹窗——没有例外，包括「请你发素材/贴链接」这种请求，"
    "也要用选项（例如「我现在上传」「我把链接贴给你」「用你已有的某条素材」）。"
)

# 规划轮的变体：那一轮还多一条正路——直接把计划交上来
POPUP_NUDGE_PLANNING = (
    "服务端核对：上面这段是在向用户提问／要用户做决定，但你没有调用 ask_user，"
    "所以界面上**不会**弹出选项卡——用户只能自己打字回答。\n"
    "现在三选一：\n"
    "① 用 ask_user 把这个问题重新问一遍（title + 2~6 个有真实差异的选项，"
    "建议的那个标 recommended=true），然后停下等用户选；\n"
    "② 诉求已经够清楚，就直接 submit_plan 把 1~3 个候选计划交上来；\n"
    "③ 信息确实不够，也照样用 ask_user 问，不要写在正文里。\n"
    "凡是要用户拿主意，就必须是弹窗——没有例外，包括「请你发素材/贴链接」这种请求。"
)

# 打回机会用尽后的兜底说明：让用户知道这句本该是个弹窗
NO_POPUP_NOTE = (
    "\n\n（服务端核对：这句本该以选项卡弹窗的形式问你，但模型没有调用提问工具，"
    "所以只能以文字呈现。你可以直接打字回复，或重新发起一次让它用弹窗问。）"
)

# 命中 looks_like_plan_invite 时打回用：该出卡的时候出了散文。
#
# 为什么这比"再弹一个窗"对：用户要的是**可点的计划卡**（能改开关、能看编排），
# 不是一个"要不要继续"的弹窗。真机实测模型把整套方案写成正文并说
# 「确认这个方案就回复我」——用户既没卡可点，也被告知要打字。
PLAN_CARD_NUDGE = (
    "你把整个方案写成了正文，并要求用户「回复」来确认——这不合规矩。"
    "方案**必须**走 submit_plan 出成计划卡：用户在卡上点选、动开关，不必打字。"
    "请立刻调用 submit_plan，把你刚才那份方案整理成 1~3 个候选计划"
    "（每步给 node / why / expectation；会影响成片效果的取值写进该步的 param_options，"
    "每个参数给 ≥2 个真实候选）。正文里不要再重复整份方案，一两句说明差异即可，"
    "也不要再要求用户回复确认——确认由卡上的点击完成。"
)


def popup_nudge(planning: bool) -> str:
    """按轮次取打回文案。"""
    return POPUP_NUDGE_PLANNING if planning else POPUP_NUDGE
